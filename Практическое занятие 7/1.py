rating = int(input("Введите рейтинг (1-10): "))

match rating:
    case 8|9|10:
        print(f"Рейтинг - {rating} -> Отличный продукт \n🫦  Рекомендую к использованию")
    case 5|6|7:
        print(f"Рейтинг - {rating} -> Средний продукт \n✨  Можно использовать")
    case 1|2|3|4:
        print(f"Рейтинг - {rating} -> Плохой продукт \n❌  Не рекомендую к использованию")
    case _:
        print("Некорректный рейтинг")