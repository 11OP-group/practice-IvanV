n = int(input("Введите четырехзначное число: "))

n1000 = n // 1000
n100 = (n // 100) % 10
n10 = (n // 10) % 10
n1 = n % 10

print("Цифра в позиции тысяч равна:", n1000)
print("Цифра в позиции сотен равна:", n100)
print("Цифра в позиции десятков равна:", n10)
print("Цифра в позиции единиц равна:", n1)