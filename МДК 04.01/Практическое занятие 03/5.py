shopping_list = ["чокопай", "чай", "американский бургер",]
shopping_list.append("кириешки")

print(shopping_list)

unique_items = set(shopping_list)

print(unique_items)

# shopping_list — это список list Он сохраняет порядок элементов и может содержать повторяющиеся значения
# unique_items — это множество set Он хранит только уникальные элементы и не сохраняет порядок