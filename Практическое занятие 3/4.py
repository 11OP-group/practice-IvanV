#1 - int - количество студентов это целое число
#2 - float - градусы имеют дробную часть
#3 - str - логин это строка
#4 - bool - у уведомления есть два состояния: включено или выключено
#5 - list - список фильмов можно хранить в виде списка
#6 - tuple - координаты должны быть неизменяемыми, поэтому их лучше хранить в виде кортежа
#7 - set - количество товаров должно быть уникальным, поэтому лучше использовать множество
#8 - dict - ключ - страна, а значение - столица